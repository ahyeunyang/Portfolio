import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { create } from 'fontkit';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'src/static/font/pretendard');
const output = path.join(root, 'src/static/scss/common/_fonts.scss');
const faces = ['// Generated by npm run fonts. Do not edit unicode ranges manually.'];
for (const file of fs.readdirSync(directory).filter(name => name.endsWith('.woff2')).sort()) {
  const font = create(fs.readFileSync(path.join(directory, file)));
  const codes = [...new Set(font.characterSet)].sort((a, b) => a - b);
  const ranges = [];
  for (let i = 0; i < codes.length; i++) {
    const start = codes[i];
    let end = start;
    while (codes[i + 1] === end + 1) end = codes[++i];
    ranges.push(`U+${start.toString(16)}${end === start ? '' : `-${end.toString(16)}`}`);
  }
  faces.push(`@font-face {
  font-family: 'Pretendard';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('../../font/pretendard/${file}') format('woff2');
  unicode-range: ${ranges.join(', ')};
}`);
}
fs.writeFileSync(output, faces.join('\n\n') + '\n');
console.log(`Generated ${faces.length - 1} local font faces.`);
